import { chromium } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import { existsSync } from 'node:fs'
const url = process.env.FORGELABS_TEST_URL
if (!url) throw new Error('Run with bun run test:integration --browser')
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || (existsSync('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome') ? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' : undefined) })
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } })
const errors: string[] = []
page.on('pageerror', error => errors.push(error.message))
await mkdir('test-results', { recursive: true })
try {
  await page.goto(url)
  await page.getByLabel('Workspace password').fill(process.env.NUXT_OPERATOR_PASSWORD!)
  await page.getByRole('button', { name: 'Open workspace' }).click()
  await page.waitForURL(url + '/')
  await page.getByRole('heading', { name: 'Overview.' }).waitFor()
  await page.getByRole('link', { name: /Lifecycle integration/ }).first().waitFor()
  await page.screenshot({ path: 'test-results/overview-desktop.png', fullPage: true })
  await page.getByRole('link', { name: 'Models', exact: true }).click()
  await page.getByRole('button', { name: 'Add model', exact: true }).click()
  await page.getByLabel('Display name').fill('Browser-created model')
  await page.getByLabel('Model repository ID').fill('openai/whisper-small')
  await page.getByRole('dialog').getByRole('button', { name: 'Add model', exact: true }).click()
  await page.getByRole('heading', { name: 'Browser-created model' }).waitFor()
  await page.goto(url + '/runs/new')
  await page.getByLabel('Experiment name').fill('Browser-created experiment')
  await page.getByLabel('Base model', { exact: true }).selectOption({ label: 'Browser-created model' })
  await page.getByLabel('Dataset', { exact: true }).selectOption({ label: 'Integration manifest' })
  await page.getByLabel('Compute worker').selectOption({ label: 'Integration worker · Online' })
  await page.screenshot({ path: 'test-results/new-experiment-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Queue experiment' }).click()
  await page.getByRole('heading', { name: 'Browser-created experiment' }).waitFor()
  await page.getByRole('button', { name: 'Stop run' }).click()
  await page.getByText('cancelled', { exact: true }).waitFor()
  await page.goto(url + '/runs')
  await page.getByRole('link', { name: 'Lifecycle integration', exact: false }).first().click()
  await page.getByText('15.00%', { exact: true }).waitFor()
  await page.screenshot({ path: 'test-results/run-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(url)
  await page.getByRole('heading', { name: 'Overview.' }).waitFor()
  await page.screenshot({ path: 'test-results/overview-mobile.png', fullPage: true })
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  if (overflow) throw new Error('Mobile page overflows horizontally')
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('link', { name: 'Compute', exact: true }).click()
  await page.getByRole('heading', { name: 'Compute.' }).waitFor()
  if (errors.length) throw new Error(errors.join('\n'))
  console.log('Browser checks passed: login, navigation, model creation, job queue/cancel, metrics, and mobile layout.')
} catch (error) {
  await page.screenshot({ path: 'test-results/browser-failure.png', fullPage: true })
  console.error('Browser failure at', page.url(), 'Page errors:', errors)
  console.error((await page.locator('body').innerText()).slice(0, 3500))
  throw error
} finally { await browser.close() }
